// Records a real agent run (real MCP server over stdio, configured LLM
// provider) into web/demo/replays/sample.js for offline replay.
// Usage: npm run record [-- --idea "Your idea"]
import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parseArgs } from "node:util";
import { createLLM } from "../agent/llm/index.mjs";
import { connectMcp } from "../agent/mcp-client.mjs";
import { runAgent } from "../agent/run-agent.mjs";

export const SAMPLE_IDEA = "An app that matches college students with local farms for paid weekend harvest shifts";
const OUT = fileURLToPath(new URL("../web/demo/replays/sample.js", import.meta.url));

const { values } = parseArgs({ options: { idea: { type: "string" } } });
const idea = (values.idea ?? SAMPLE_IDEA).trim();
if (idea.length < 3 || idea.length > 500) {
  console.error("--idea must be 3-500 characters");
  process.exit(1);
}

const env = { ...process.env };
const providerName = String(env.LLM_PROVIDER ?? "").trim().toLowerCase() || "mock";
if (providerName === "mock" && env.MOCK_LATENCY_MS === undefined) env.MOCK_LATENCY_MS = "1100";

const llm = createLLM(env);
if (!llm.ready) {
  console.error(`Provider "${llm.name}" is not ready: ${llm.reason}`);
  process.exit(1);
}

console.error(`Recording with ${llm.name} (${llm.model})…`);
const events = [];
const mcp = await connectMcp({ name: "replay-recorder" });
try {
  await runAgent({ idea, llm, client: mcp.client, emit: (e) => events.push(e) });
} finally {
  await mcp.close().catch(() => {});
}

const failed = events.filter((e) => e.type === "error" || (e.type === "tool_result" && e.isError));
if (failed.length || events.at(-1)?.type !== "run_end" || !events.some((e) => e.type === "final")) {
  console.error("Run did not complete cleanly; not writing the replay.");
  for (const e of failed) console.error(" ", e.type, e.message ?? e.name);
  process.exit(1);
}

const replay = {
  version: 1,
  recordedAt: new Date().toISOString(),
  idea,
  provider: llm.name,
  model: llm.model,
  events,
};
const body =
  "// Generated by `npm run record` from a real agent run. Do not edit by hand.\n" +
  `window.DEMO_REPLAY = ${JSON.stringify(replay, null, 2)};\n`;
await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, body);
console.error(`Wrote ${path.relative(process.cwd(), OUT)} (${events.length} events, ${events.at(-1).ms} ms)`);
